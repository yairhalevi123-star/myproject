var boga = document.querySelector(".Bugatti");
boga.addEventListener("click", () => {
  var price = document.querySelector(".price");
  price.innerHTML = "100000$";
  price.style.backgroundColor = "orange";
  boga.innerHTML = "clicked";
});
boga.addEventListener("mouseout", () => {
  var price = document.querySelector(".price");
  price.innerHTML = "";
  price.style.backgroundColor = "orage";
  boga.innerHTML = "more...";
});
